#!/usr/bin/env python3
"""Results-and-comparison workbook for the 50-trace evaluation, built only from the CSVs.

  build/venv/Scripts/python experiments/scripts/make_workbook_50trace.py [--res results_50trace]

Writes <res>/TFL-TAGE-SC-L_50trace_Results.xlsx (needs openpyxl).
"""
import argparse, csv, os

from openpyxl import Workbook
from openpyxl.drawing.image import Image
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEAD = PatternFill("solid", fgColor="DCE9F9")
PROP = PatternFill("solid", fgColor="EAF2FC")


def read(p):
    return list(csv.DictReader(open(p)))


def num(x):
    try:
        v = float(x)
        return int(v) if v.is_integer() and "." not in x and "e" not in x.lower() else v
    except (TypeError, ValueError):
        return x


def sheet(wb, title, rows, cols=None, note=None, highlight=None):
    ws = wb.create_sheet(title)
    cols = cols or list(rows[0])
    r0 = 1
    if note:
        ws.cell(1, 1, note).font = Font(italic=True)
        r0 = 3
    for j, c in enumerate(cols, 1):
        cell = ws.cell(r0, j, c)
        cell.font, cell.fill = Font(bold=True), HEAD
        cell.alignment = Alignment(wrap_text=True, vertical="top")
    for i, r in enumerate(rows, r0 + 1):
        for j, c in enumerate(cols, 1):
            cell = ws.cell(i, j, num(r.get(c, "")))
            if isinstance(cell.value, float):
                cell.number_format = "0.0000"
            if highlight and highlight(r):
                cell.fill = PROP
    for j, c in enumerate(cols, 1):
        ws.column_dimensions[get_column_letter(j)].width = max(10, min(40, len(c) + 2))
    ws.freeze_panes = ws.cell(r0 + 1, 2)
    return ws


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", default=os.path.join(ROOT, "results_50trace"))
    a = ap.parse_args()
    wb = Workbook()
    ws = wb.active
    ws.title = "README"
    lines = [
        "TFL-TAGE-SC-L — 50-trace ChampSim evaluation: results and comparison",
        "",
        "All sheets are copies of the CSV files in results_50trace/ (generated by experiments/scripts/analyze_50trace.py",
        "from the raw ChampSim outputs in experiments/results/M50_50M_200M/). No value was entered by hand.",
        "",
        "Summary      one row per predictor: storage, arithmetic/geometric mean IPC, speedup vs bimodal, mean MPKI, pooled accuracy, runtime",
        "Comparison   TFL-TAGE-SC-L vs each baseline: MPKI reduction, geomean IPC improvement, per-trace wins/ties/losses, extremes",
        "Subsets      the same aggregates on: all traces, original 10, additional 40, SPECint, SPECfp",
        "PerTrace     one row per trace: IPC, MPKI, accuracy of every predictor; proposed-vs-baseline deltas",
        "Raw          one row per run (350): status, exact counters, metrics, log file",
        "Manifest     the 50 traces with size, sha256, md5 (= Zenodo md5)",
        "Figures      the generated graphs",
        "",
        "Window: 50M warm-up + 200M measured instructions per trace; ChampSim 2021, 1 core, no prefetchers, LRU LLC.",
        "MPKI and accuracy count all branch types (ChampSim's definition); cond_* columns count conditional branches only.",
        "Mean IPC = arithmetic mean; geomean IPC = geometric mean; speedup = geometric mean of per-trace IPC ratios.",
    ]
    for i, l in enumerate(lines, 1):
        ws.cell(i, 1, l).font = Font(bold=(i == 1), size=12 if i == 1 else 11)
    ws.column_dimensions["A"].width = 130

    prop = lambda r: r.get("predictor") == "tsl_proposed"
    sheet(wb, "Summary", read(os.path.join(a.res, "summary.csv")), highlight=prop)
    sheet(wb, "Comparison", read(os.path.join(a.res, "comparison_vs_baselines.csv")),
          note="TFL-TAGE-SC-L (proposed) relative to each baseline")
    sheet(wb, "Subsets", read(os.path.join(a.res, "subset_summary.csv")), highlight=prop)
    sheet(wb, "PerTrace", read(os.path.join(a.res, "per_trace_results.csv")))
    sheet(wb, "Raw", read(os.path.join(a.res, "raw_results.csv")), highlight=prop)
    sheet(wb, "Manifest", read(os.path.join(a.res, "trace_manifest.csv")))

    wf = wb.create_sheet("Figures")
    row = 1
    figdir = os.path.join(a.res, "figures")
    for fn in sorted(os.listdir(figdir), key=lambda s: int(s[3:].split("_")[0]) if s[3:].split("_")[0].isdigit() else 99):
        if not fn.endswith(".png"):
            continue
        wf.cell(row, 1, fn).font = Font(bold=True)
        img = Image(os.path.join(figdir, fn))
        scale = 900 / img.width
        img.width, img.height = int(img.width * scale), int(img.height * scale)
        wf.add_image(img, f"A{row + 1}")
        row += int(img.height / 20) + 4
    out = os.path.join(a.res, "TFL-TAGE-SC-L_50trace_Results.xlsx")
    wb.save(out)
    print("wrote", out)


if __name__ == "__main__":
    main()
